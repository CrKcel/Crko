package com.crko.state

import com.crko.domain.AppState
import com.crko.i18n.Strings
import kotlinx.datetime.LocalDate
import kotlinx.datetime.TimeZone
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import kotlin.time.Clock

/**
 * Keeps the platform notifications in line with the state. The plan is computed record by record,
 * reusing the fragments of records whose content and planning environment did not change, and only
 * the delta against the last applied plan reaches the platform.
 *
 * Extracted from [AppStateHolder] so the facade stays inside its line budget. The coordinator also
 * owns the app-prompt budget and the extra reminders that do not come from stored records, such as
 * the focus-session end notification.
 */
internal class ReminderCoordinator(
    private val scope: CoroutineScope,
    private val scheduler: ReminderScheduler,
    private val clock: Clock,
    private val dispatcher: CoroutineDispatcher,
    private val state: () -> AppState,
    private val today: () -> LocalDate,
    private val strings: () -> Strings,
    /** App prompts allowed per day; user alarms never read this. */
    private val coachBudget: () -> Int,
    /** Reminders generated by runtime state rather than a stored record (focus session end). */
    private val dynamicReminders: () -> List<ScheduledReminder> = { emptyList() },
) {
    private var job: Job? = null
    private val mutex = Mutex()

    /** Fingerprints of the plan the scheduler last confirmed; the diff source of the next pass. */
    private var appliedReminders: Map<String, ReminderFingerprint> = emptyMap()

    /** Set at startup; the first pass that runs replaces instead of diffing, even after an edit. */
    private var fullReplacementPending = true

    /**
     * Reminders of one record, kept so a pass re-walks only records whose content changed. The
     * environment the plan is projected through (device zone, today) is part of the cache key:
     * a rollover or a zone change invalidates every fragment at once.
     */
    private data class ReminderFragment(val source: Any, val reminders: List<ScheduledReminder>)

    private var fragments: Map<String, ReminderFragment> = emptyMap()
    private var fragmentZoneId: String? = null
    private var fragmentToday: LocalDate? = null

    /**
     * Recomputes the plan and hands the delta to the platform. One job at a time — and the mutex
     * keeps that promise even though cancelling a job does not stop a pass that is already running,
     * so an older pass can never land after a newer one.
     */
    fun schedule(forceFull: Boolean = false, delayMillis: Long = 0) {
        job?.cancel()
        job = scope.launch {
            if (delayMillis > 0) delay(delayMillis)
            mutex.withLock {
                runCatching {
                    val plan = withContext(dispatcher) { computePlan() }
                    // An edit that lands before the delayed launch pass still needs the full
                    // replacement, because nothing has reached the platform yet.
                    val replaceAll = forceFull || fullReplacementPending
                    fullReplacementPending = false
                    val applied = if (replaceAll) {
                        scheduler.replaceAll(plan)
                    } else {
                        val diff = diffReminders(appliedReminders, plan)
                        // An empty delta leaves the platform alone; the bookkeeping is the same.
                        diff.isEmpty || scheduler.execute(diff.cancelKeys, diff.register)
                    }
                    if (applied) appliedReminders = plan.associate { it.key to it.fingerprint }
                }
            }
        }
    }

    /**
     * Asks for notification permission the first time the user gives an event a reminder. Scheduling
     * itself stays silent about permissions so startup never shows a prompt; once the answer is in,
     * the plan is pushed again because the pass that ran without permission registered nothing.
     */
    fun ensurePermission() {
        scope.launch {
            runCatching {
                if (scheduler.ensurePermission()) schedule()
            }
        }
    }

    /**
     * The current plan: per-record fragments re-filtered against [Clock.now], merged with the
     * dynamic reminders, budgeted against the coach allowance, earliest first and capped.
     */
    private fun computePlan(): List<ScheduledReminder> {
        val current = state()
        val zone = TimeZone.currentSystemDefault()
        val nowMillis = clock.now().toEpochMilliseconds()
        val currentToday = today()
        val text = strings()
        val reusable = if (zone.id == fragmentZoneId && currentToday == fragmentToday) fragments else emptyMap()
        val next = HashMap<String, ReminderFragment>()
        val plan = mutableListOf<ScheduledReminder>()

        fun fragment(key: String, record: Any, fresh: () -> List<ScheduledReminder>) {
            val cached = reusable[key]
            val reminders = if (cached != null && cached.source == record) cached.reminders else fresh()
            next[key] = ReminderFragment(record, reminders)
            // A cached trigger can have fired since its fragment was built; the fresh ones already
            // skip the past, so the merge filters both against the current instant.
            reminders.forEach { if (it.triggerAtMillis > nowMillis) plan += it }
        }

        current.events.forEach { event ->
            val id = event.id ?: return@forEach
            fragment("e:$id", event) { planEventReminders(event, currentToday, zone, nowMillis, text) }
        }
        current.todos.forEach { todo ->
            fragment("t:${todo.id}", todo) { planTodoReminders(todo, currentToday, zone, nowMillis, text) }
        }
        dynamicReminders().forEach { reminder ->
            if (reminder.triggerAtMillis > nowMillis) plan += reminder
        }
        fragments = next
        fragmentZoneId = zone.id
        fragmentToday = currentToday
        return applyReminderPolicy(plan, coachBudget(), zone)
            .sortedBy { it.triggerAtMillis }
            .take(MaxScheduledReminders)
    }

    /** Marks the next pass as a full replacement and runs it immediately. */
    fun requestFullReplacement(delayMillis: Long = 0) {
        fullReplacementPending = true
        schedule(forceFull = true, delayMillis = delayMillis)
    }
}
